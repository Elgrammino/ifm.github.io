const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const dir=path.join(__dirname,'..','prototypes','next-event');
test('all three previews switch, open a real event and save independently of the app',()=>{
  assert.ok(fs.existsSync(path.resolve(dir,'../../hero.jpg')));
  assert.ok(fs.existsSync(path.resolve(dir,'../../m500.woff2')));
  const callbacks={};
  const el=()=>({innerHTML:'',style:{},dataset:{},textContent:'',addEventListener(name,fn){this[name]=fn},setAttribute(){},removeAttribute(){},toggleAttribute(){},showModal(){this.open=true},close(){this.open=false}});
  const stage=el(),saved=el(),dialog=el(),time=el(),title=el(),desc=el(),save=el(),close=el(),highlight=el();
  const items=Array.from({length:3},(_,i)=>({...el(),offsetWidth:80,offsetLeft:80*i}));
  const picker={querySelector:s=>s.includes('highlight')?highlight:null,querySelectorAll:()=>items,setAttribute(){}};
  const ids={stage,saved,detail:dialog,'detail-time':time,'detail-title':title,'detail-desc':desc,'detail-save':save,'detail-close':close};
  const document={getElementById:id=>ids[id],querySelector:()=>picker,addEventListener:(name,fn)=>callbacks[name]=fn};
  const location={search:'',toString:()=> 'https://example.org/demo/prototypes/next-event/'};
  const ctx={window:{addEventListener(){}},document,location,history:{replaceState(){}},Date,Math,URL,URLSearchParams,Set,requestAnimationFrame:fn=>fn()};
  vm.createContext(ctx);
  for(const file of ['announcement.js','route.js','countdown.js'])vm.runInContext(fs.readFileSync(path.join(dir,file),'utf8'),ctx);
  const html=fs.readFileSync(path.join(dir,'index.html'),'utf8');
  vm.runInContext(html.match(/<script>([\s\S]*?)<\/script>/)[1],ctx);
  assert.match(stage.innerHTML,/class="ann"/);
  items[1].click(); assert.match(stage.innerHTML,/class="route"/);
  items[2].click(); assert.match(stage.innerHTML,/class="count"/);
  stage.click({target:{closest:()=>({dataset:{action:'open',id:'a1'}})}});
  assert.equal(dialog.open,true); assert.equal(title.textContent,'Регистрация участников');
  close.click();assert.equal(dialog.open,false);
  stage.click({target:{closest:()=>({dataset:{action:'save',id:'a1'}})}});
  assert.match(saved.innerHTML,/Регистрация участников/);
  assert.match(stage.innerHTML,/aria-pressed="true"/);
  save.dataset.id='a1';save.click({currentTarget:save});assert.match(saved.innerHTML,/Сохранённые события появятся/);
  callbacks.keydown({target:{tagName:'BODY',isContentEditable:false},key:'1',metaKey:false,ctrlKey:false,altKey:false});
  assert.match(stage.innerHTML,/class="ann"/);
});
